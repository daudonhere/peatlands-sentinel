def generate_excel_report(run_data: dict[str, Any]) -> io.BytesIO:
    wb = openpyxl.Workbook()
    header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    header_fill = PatternFill(
        start_color="1E293B", end_color="1E293B", fill_type="solid"
    )

    ws_summary = wb.active
    ws_summary.title = "Executive Summary"
    ws_summary.append(["Parameter", "Value"])
    for col in ["A", "B"]:
        ws_summary[f"{col}1"].font = header_font
        ws_summary[f"{col}1"].fill = header_fill

    ai_report = run_data.get("ai_report", {})
    summary_rows = [
        ["Run ID", run_data.get("id")],
        ["Execution Timestamp", run_data.get("created_at")],
        ["Analysis Objective", run_data.get("target")],
        ["Estimated AOI Area (Hectares)", run_data.get("area_hectares")],
        ["Threat Level", ai_report.get("threat_level")],
        ["Peat Moisture Status", ai_report.get("peat_moisture_status")],
        ["Fire Risk Narrative", ai_report.get("fire_risk_summary")],
        ["Classification Reasoning", ai_report.get("classification_reasoning")],
    ]
    for row in summary_rows:
        ws_summary.append(row)

    ws_summary.column_dimensions["A"].width = 28
    ws_summary.column_dimensions["B"].width = 70

    ws_metrics = wb.create_sheet(title="Telemetry & Indices")
    ws_metrics.append(
        ["Index / Sensor", "Observed Value", "Standard Range", "Description"]
    )
    for cell in ws_metrics["1:1"]:
        cell.font = header_font
        cell.fill = header_fill

    metrics = run_data.get("metrics", {})
    metric_rows = [
        [
            "NDVI (Vegetation Index)",
            metrics.get("mean_ndvi"),
            "-1.0 to 1.0",
            "Canopy density and vigor",
        ],
        [
            "NDWI (Water Index)",
            metrics.get("mean_ndwi"),
            "-1.0 to 1.0",
            "Surface moisture and open water",
        ],
        [
            "NBR (Normalized Burn Ratio)",
            metrics.get("mean_nbr"),
            "-1.0 to 1.0",
            "Chlorophyll and water absorption",
        ],
        [
            "BSI (Bare Soil Index)",
            metrics.get("mean_bsi"),
            "-1.0 to 1.0",
            "Ground clearing and mineral exposure",
        ],
        [
            "Max dNBR (Burn Severity)",
            metrics.get("max_dnbr"),
            "-1.0 to 2.0",
            "Fire scar difference index",
        ],
        [
            "SAR Cross-Ratio (VH/VV dB)",
            metrics.get("mean_sar_cross_ratio"),
            "Negative dB",
            "Soil moisture and roughness",
        ],
    ]
    for r in metric_rows:
        ws_metrics.append(r)

    ws_metrics.column_dimensions["A"].width = 30
    ws_metrics.column_dimensions["B"].width = 18
    ws_metrics.column_dimensions["C"].width = 18
    ws_metrics.column_dimensions["D"].width = 45

    ws_trans = wb.create_sheet(title="Land Transitions")
    ws_trans.append(
        ["Baseline Class", "Transitioned Class", "Area (Hectares)", "Share (%)"]
    )
    for cell in ws_trans["1:1"]:
        cell.font = header_font
        cell.fill = header_fill

    transitions = run_data.get("transitions", [])
    for t in transitions:
        ws_trans.append(
            [
                t.get("from_class"),
                t.get("to_class"),
                t.get("area_hectares"),
                t.get("change_percentage"),
            ]
        )

    ws_trans.column_dimensions["A"].width = 24
    ws_trans.column_dimensions["B"].width = 24
    ws_trans.column_dimensions["C"].width = 18
    ws_trans.column_dimensions["D"].width = 14

    output = io.BytesIO()
    wb.save(output)
    output.seek(0)
    return output


def create_export_zip_package(run_data: dict[str, Any]) -> io.BytesIO:
    zip_buffer = io.BytesIO()
    run_id = run_data.get("id", "run")

    with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zip_file:
        geojson_str = json.dumps(run_data.get("geojson", {}), indent=2)
        zip_file.writestr(f"{run_id}_boundary.geojson", geojson_str)

        summary_str = json.dumps(run_data, indent=2)
        zip_file.writestr(f"{run_id}_summary.json", summary_str)

        excel_stream = generate_excel_report(run_data)
        zip_file.writestr(f"{run_id}_report.xlsx", excel_stream.getvalue())

        ai_report = run_data.get("ai_report", {})
        bbox = run_data.get("geojson", {}).get("bbox", [0, 0, 0, 0])
        svg_content = generate_svg_preview(
            target=run_data.get("target", "analysis"),
            threat=ai_report.get("threat_level", "Low"),
            bbox=bbox,
            area_ha=run_data.get("area_hectares", 0.0),
        )
        zip_file.writestr(f"{run_id}_preview.svg", svg_content)

        tif_bytes = generate_geotiff_raster(bbox)
        zip_file.writestr(f"{run_id}_raster.tif", tif_bytes)

        qgis_xml = generate_qgis_project_xml(
            run_id, f"{run_id}_boundary.geojson", f"{run_id}_raster.tif"
        )
        zip_file.writestr(f"{run_id}_project.qgs", qgis_xml)

    zip_buffer.seek(0)
    return zip_buffer
